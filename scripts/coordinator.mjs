#!/usr/bin/env node
// The coordinator's view of the issue queue, by code (GOVERNANCE sections 3, 4 and 8). Plain code, no model, no token:
// a thread has no GitHub access from scripts, so this prints the calls to make, or reads their raw result from --facts.
//   node scripts/coordinator.mjs next [--facts FILE]
//        without --facts: the GitHub calls that collect the raw queue, and where to save it.
//        with --facts: a table of open `harness-idea` and `studio-backlog` issues in the written default order
//        (daily use, then safety, then capability, then older first). The Owner's own order always overrides it.
//   node scripts/coordinator.mjs triage <n> accept [--impact daily-use|safety|capability] [--why "<text>"] [--facts FILE]
//   node scripts/coordinator.mjs triage <n> merge <m> [--facts FILE]
//   node scripts/coordinator.mjs triage <n> decline "<reason>" [--facts FILE]
//        the exact label change and the single trail comment (intake.md section 4), as calls to make word for word.
// Facts file: {"issues":[{number,title,labels:[name],created_at,body}], "prs":[{number,title,files?:[path]}]} (open ones only).
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const IDEA = ["harness-idea", "studio-backlog"];
const IMPACT = ["daily-use", "safety", "capability"];
const REPO = { owner: "ildruido", repo: "app-studio" };
const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
export const FACTS_FILE = ".git/coordinator-facts.json";

const names = (it) => (it.labels ?? []).map((l) => l.name ?? l);
const ageDays = (it, now) => Math.max(0, Math.floor((now - Date.parse(it.created_at)) / 864e5));

/** Area: the word before the first colon after any `[tag]` prefix, else the conventional-commit scope/type. */
export function area(title) {
  const t = String(title).replace(/^\s*\[[^\]]*\]\s*/, "");
  const m = t.match(/^([\w./-]+?)(?:\(([^)]*)\))?\s*:/);
  return m ? (m[2] || m[1]).toLowerCase() : "general";
}

/** Open issues this one says it depends on ("depends on #N", "after #N", "blocked by #N"), kept only when still open. */
export function dependsOn(it, open) {
  const out = new Set();
  for (const m of String(it.body ?? "").matchAll(/(?:depends on|blocked by|after)\s+#(\d+)/gi)) {
    const n = Number(m[1]);
    if (n !== it.number && open.has(n)) out.add(n);
  }
  return [...out].sort((a, b) => a - b);
}

const words = (s) => new Set(String(s).toLowerCase().replace(/^\s*\[[^\]]*\]\s*/, "").match(/[a-z][a-z0-9-]{3,}/g) ?? []);
/** Likely duplicates: open issues whose title words overlap at least half (Jaccard). A hint; the model judges. */
export function dupes(it, issues) {
  const a = words(it.title);
  return issues
    .filter((o) => o.number !== it.number)
    .filter((o) => {
      const b = words(o.title);
      const inter = [...a].filter((w) => b.has(w)).length;
      return a.size && b.size && inter / (a.size + b.size - inter) >= 0.5;
    })
    .map((o) => o.number);
}

/** Open PRs touching the same area: by changed file path when the facts list files, else by area word in the PR title. */
export function blockedBy(it, prs) {
  const a = area(it.title);
  if (a === "general") return [];
  return prs
    .filter((p) => (p.files?.length ? p.files.some((f) => f.toLowerCase().includes(a)) : words(p.title).has(a) || area(p.title) === a))
    .map((p) => p.number);
}

export function rank(it) {
  const i = IMPACT.findIndex((x) => names(it).includes(`impact:${x}`));
  return i === -1 ? IMPACT.length : i;
}

export function table(facts, now = Date.now()) {
  const issues = (facts.issues ?? []).filter((i) => names(i).some((l) => IDEA.includes(l)));
  const open = new Set(issues.map((i) => i.number));
  const prs = facts.prs ?? [];
  const rows = issues.map((it) => ({
    it,
    dep: dependsOn(it, open),
    blocked: blockedBy(it, prs),
    dup: dupes(it, issues),
    r: rank(it),
  }));
  rows.sort((x, y) => x.r - y.r || ageDays(y.it, now) - ageDays(x.it, now) || x.it.number - y.it.number);
  const fmt = (a, p = "#") => (a.length ? a.map((n) => p + n).join(",") : "-");
  const lines = ["rank | issue | label | impact | age | area | depends on | blocked by PR | likely dup"];
  rows.forEach(({ it, dep, blocked, dup, r }, k) => {
    const lab = names(it).find((l) => IDEA.includes(l));
    const imp = r < IMPACT.length ? IMPACT[r] : "unlabelled";
    lines.push([k + 1, `#${it.number} ${it.title.replace(/^\s*\[harness-idea\]\s*/i, "").slice(0, 70)}`, lab, imp, `${ageDays(it, now)}d`, area(it.title), fmt(dep), fmt(blocked, "PR #"), fmt(dup)].join(" | "));
  });
  lines.push("", "Default order only (section 4): daily use, then safety, then capability, oldest first. Issues with a dependency or a blocking PR should wait. The Owner's own order overrides it. Unlabelled impact means triage has not set one: `triage <n> accept --impact ...`.");
  if (!rows.length) return "No open harness-idea or studio-backlog issues in the facts.";
  return lines.join("\n");
}

const call = (tool, args) => `${tool} ${JSON.stringify(args)}`;

export function collectHelp() {
  return [
    `Collect the raw queue (no interpretation) and write it to ${FACTS_FILE}:`,
    "1. " + call("mcp__github__list_issues", { ...REPO, state: "OPEN", labels: ["studio-backlog"], perPage: 100 }),
    "2. " + call("mcp__github__list_issues", { ...REPO, state: "OPEN", labels: ["harness-idea"], perPage: 100 }),
    "3. " + call("mcp__github__list_pull_requests", { ...REPO, state: "open", perPage: 30 }),
    `Write {"issues":[{number,title,labels,created_at,body}...from 1 and 2],"prs":[{number,title}...from 3]} to ${FACTS_FILE}, then run: node scripts/coordinator.mjs next --facts ${FACTS_FILE}`,
  ].join("\n");
}

export function triage(n, action, rest, facts, opts = {}) {
  const it = (facts?.issues ?? []).find((i) => i.number === n);
  const base = it ? names(it).filter((l) => !IDEA.includes(l) && !l.startsWith("impact:")) : [];
  const keep = it ? names(it).filter((l) => l.startsWith("impact:")) : [];
  const note = it ? "" : "\nNo facts given: the labels below are only the new ones. Use `--facts` so other labels are kept, or add them by hand.";
  if (action === "accept") {
    const imp = opts.impact;
    if (imp && !IMPACT.includes(imp)) throw new Error(`--impact must be one of ${IMPACT.join(", ")}`);
    const labels = [...base, "studio-backlog", ...(imp ? [`impact:${imp}`] : keep)];
    const body = `Accepted (triage ${opts.date}). ${opts.why || "Why and what it depends on: add with --why."}${imp ? ` Impact: ${imp}.` : ""}${FOOTER}`;
    return [call("mcp__github__issue_write", { ...REPO, method: "update", issue_number: n, labels }), call("mcp__github__add_issue_comment", { ...REPO, issue_number: n, body })].join("\n") + note;
  }
  if (action === "merge") {
    const m = Number(rest[0]);
    if (!Number.isInteger(m) || m === n) throw new Error("merge needs the other issue number: triage <n> merge <m>");
    return [
      call("mcp__github__add_issue_comment", { ...REPO, issue_number: m, body: `New evidence from #${n}: add one line of it here.${FOOTER}` }),
      call("mcp__github__add_issue_comment", { ...REPO, issue_number: n, body: `Duplicate of #${m}.${FOOTER}` }),
      call("mcp__github__issue_write", { ...REPO, method: "update", issue_number: n, state: "closed", state_reason: "duplicate", duplicate_of: m }),
    ].join("\n");
  }
  if (action === "decline") {
    const reason = rest.join(" ").trim();
    if (!reason) throw new Error('decline needs a one-line reason: triage <n> decline "<reason>"');
    return [call("mcp__github__add_issue_comment", { ...REPO, issue_number: n, body: `Declined: ${reason}${FOOTER}` }), call("mcp__github__issue_write", { ...REPO, method: "update", issue_number: n, state: "closed", state_reason: "not_planned" })].join("\n") + note;
  }
  throw new Error("action must be accept, merge or decline");
}

function parse(argv) {
  const pos = [];
  const opt = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith("--")) opt[argv[i].slice(2)] = argv[++i];
    else pos.push(argv[i]);
  }
  return { pos, opt };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { pos, opt } = parse(process.argv.slice(2));
  try {
    const facts = opt.facts ? JSON.parse(readFileSync(opt.facts, "utf8")) : null;
    if (pos[0] === "next") console.log(facts ? table(facts) : collectHelp());
    else if (pos[0] === "triage" && Number.isInteger(Number(pos[1])) && pos[2]) {
      console.log(triage(Number(pos[1]), pos[2], pos.slice(3), facts, { impact: opt.impact, why: opt.why, date: new Date().toISOString().slice(0, 10) }));
    } else {
      console.error("usage: coordinator.mjs next [--facts FILE] | triage <n> accept|merge <m>|decline \"<reason>\" [--facts FILE]");
      process.exit(2);
    }
  } catch (e) {
    console.error(e.message);
    process.exit(2);
  }
}
